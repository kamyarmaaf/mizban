export const sampleArticle = sampleArticles[0];

export function loadArticles(): Article[] {
  const stored = localStorage.getItem('userArticles');
  const userArticles = stored ? JSON.parse(stored) : [];

  return [...sampleArticles, ...userArticles];
}

export function saveArticle(article: Article): void {
  const stored = localStorage.getItem('userArticles');
  const articles = stored ? JSON.parse(stored) : [];
  articles.unshift(article);
  localStorage.setItem('userArticles', JSON.stringify(articles));
}

export function deleteArticle(articleId: string): void {
  const stored = localStorage.getItem('userArticles');
  const articles = stored ? JSON.parse(stored) : [];
  const filtered = articles.filter((a: Article) => a.id !== articleId);
  localStorage.setItem('userArticles', JSON.stringify(filtered));
}

export function getArticleById(articleId: string): Article | null {
  const foundInSamples = sampleArticles.find(a => a.id === articleId);
  if (foundInSamples) {
    return foundInSamples;
  }

  const stored = localStorage.getItem('userArticles');
  const articles = stored ? JSON.parse(stored) : [];
  return articles.find((a: Article) => a.id === articleId) || null;
}

export function updateArticleStats(articleId: string, updates: { views?: number; likes?: number }): void {
  const isSampleArticle = sampleArticles.some(a => a.id === articleId);
  if (isSampleArticle) {
    return;
  }

  const stored = localStorage.getItem('userArticles');
  const articles = stored ? JSON.parse(stored) : [];
  const index = articles.findIndex((a: Article) => a.id === articleId);

  if (index !== -1) {
    if (updates.views !== undefined) {
      articles[index].views = updates.views;
    }
    if (updates.likes !== undefined) {
      articles[index].likes = updates.likes;
    }
    localStorage.setItem('userArticles', JSON.stringify(articles));
  }
}
